import io, os, sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')


def patch(fname, old, new):
    p = os.path.join(ROOT, 'game', 'data', fname)
    with io.open(p, 'r', encoding='utf-8') as f:
        txt = f.read()
    if new in txt:
        print(f"OK（已改过，跳过）: {fname} …{new[-14:]}」")
        return
    assert old in txt, f"{fname} 找不到目标串: {old[:36]}"
    assert old != new
    txt = txt.replace(old, new)
    with io.open(p, 'w', encoding='utf-8', newline='') as f:
        f.write(txt)
    print(f"OK: {fname}  「…{old[-14:]}」→「…{new[-14:]}」")


