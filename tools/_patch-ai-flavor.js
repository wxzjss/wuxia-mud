let fileCount = 0, subCount = 0, missCount = 0;
const byFile = {};
for (const [f, oldT, news] of SUBS) (byFile[f] = byFile[f] || []).push([oldT, news]);

for (const f of Object.keys(byFile)) {
  const p = path.join(DATA, f);
  let txt = fs.readFileSync(p, 'utf8');
  const before = txt;
  for (const [oldT, news] of byFile[f]) {
    let idx = -1, done = 0;
    for (let i = 0; i < news.length; i++) {
      idx = txt.indexOf(oldT, idx + 1);
      if (idx < 0) { console.log('  ✘ 第 ' + (i + 1) + ' 处找不到：' + f + ' / ' + oldT.slice(0, 18)); missCount++; break; }
      txt = txt.slice(0, idx) + news[i] + txt.slice(idx + oldT.length);
      idx = idx + news[i].length - oldT.length;
      done++; subCount++;
    }
    if (done && done < news.length) { /* 已在循环里报过 */ }
    /* 若新串比旧串短，后面的仍能对上（用 indexOf 逐次推进，不做全局替换） */
  }
  if (txt !== before) { fs.writeFileSync(p, txt, 'utf8'); fileCount++; console.log('  ✔ ' + f + ' 已改'); }
}
console.log('\n改了 ' + fileCount + ' 个文件 · ' + subCount + ' 处替换' + (missCount ? ' · ' + missCount + ' 处未命中' : ''));
process.exit(missCount ? 1 : 0);
