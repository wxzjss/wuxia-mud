/* ---------- 确定性取句 ---------- */
function H(s) { let h = 2166136261; for (let i = 0; i < String(s).length; i++) { h ^= String(s).charCodeAt(i); h = Math.imul(h, 16777619); } return h >>> 0; }
const pick = (arr, salt) => arr[H(salt) % arr.length];
/* ⚠️ 组内**轮转**取变体（不是哈希取模）：
   哈希在样本小的时候会撞堆 —— 实测 21 个看门人里有 9 个抽到了同一句口头禅，
   而变体池里明明有 5 句。轮转保证「同一组里相邻的两个人必不重样」。
   仍然完全确定（只跟排序后的序号有关），重跑结果一致。 */
const pickSeq = (arr, seq) => arr[((seq % arr.length) + arr.length) % arr.length];
const fill = (tpl, ctx) => String(tpl).replace(/%\{(\w+)\}/g, (m, k) => ctx[k] !== undefined ? ctx[k] : m);

