const byFile = {};
for (const [f, oldT, news] of SUBS) (byFile[f] = byFile[f] || []).push([oldT, news]);

let files = 0, done = 0, miss = 0;
for (const f of Object.keys(byFile)) {
  const p = path.join(DATA, f);
  let txt = fs.readFileSync(p, 'utf8');
  const before = txt;
  for (const [oldT, news] of byFile[f]) {
    let idx = -1;
    for (let i = 0; i < news.length; i++) {
      idx = txt.indexOf(oldT, idx + 1);
      if (idx < 0) break;                       /* 该串只出现这么多次 → 剩余变体不用 */
      txt = txt.slice(0, idx) + news[i] + txt.slice(idx + oldT.length);
      idx = idx + news[i].length - oldT.length;
      done++;
    }
    if (idx < 0) { console.log('  · ' + f + '：' + oldT.slice(0, 16) + '… 已无更多，跳过'); }
    else if (txt.indexOf(oldT, idx + 1) >= 0) { console.log('  ✘ ' + f + '：' + oldT.slice(0, 16) + '… 变体不够'); miss++; }
  }
  if (txt !== before) { fs.writeFileSync(p, txt, 'utf8'); files++; console.log('  ✔ ' + f); }
}
console.log('\n第二批：' + files + ' 个文件 · ' + done + ' 处替换' + (miss ? ' · ' + miss + ' 处变体不足' : ''));
process.exit(miss ? 1 : 0);
