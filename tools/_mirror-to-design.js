for (const f of fs.readdirSync(DESIGN)) {
  if (!/\.json$/.test(f)) continue;
  const p = path.join(DESIGN, f);
  let s;
  try { s = fs.readFileSync(p, 'utf8'); } catch (e) { continue; }
  const before = s;
  for (const [oldT, newT] of PAIRS) {
    if (s.indexOf(oldT) < 0) { miss++; continue; }
    s = s.split(oldT).join(newT);
    hit++;
  }
  if (s !== before) { fs.writeFileSync(p, s, 'utf8'); files++; console.log('  ✔ design/' + f); }
}
