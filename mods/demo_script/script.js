/* ============================================================================
 * script.js —— 武侠行 Mod 的「高级写法」
 * ============================================================================
 * mod.json 能做的事（加房间、加人、加武学）它都做不了，但它能做 mod.json
 * **做不到**的事：真正的判断、真正的记忆、真正的一条新指令。
 *
 * 这个文件在**隔离沙箱**里跑：没有 require / process / 文件系统 / 网络 / 定时器，
 * 顶层执行和每次回调都有超时（死循环会被中断，不会把服务挂住）。
 * 你不是在给游戏打补丁，是在一个安全的盒子里写小逻辑。
 *
 * 全局只有一个东西可用：`wx`。它所有的本事见下（也见游戏里的「Mod 制作器 → 功能 Mod」）。
 *
 *   wx.log(msg)            写进「Mod 日志」（排错用）
 *   wx.state               会**随存档保存**的小账本（存玩家身上，读档还在）
 *   wx.command(名, 函数)    注册一条新指令（不能覆盖游戏原有指令，会明确拒绝）
 *   wx.on(事件, 函数)       监听世界事件：onTick / onDayTick / onKill / onLevelUp /
 *                          onEnter / onHeal / onRumorBorn / onKinsmanWitness
 *   wx.msg(文本)           往屏幕上加一行（也可以直接 return）
 *   wx.me()  wx.here()     看自己 / 看眼前有什么
 *   wx.has(id)  wx.count(id)  wx.flag(名)  wx.get(名)
 *   wx.give(id, 个数)  wx.money(n)  wx.pot(n)  wx.hp(n)
 *   wx.go(房间id)  wx.rng()  wx.chance(概率)  wx.set(名, 值)
 *
 * 回调 return 什么，玩家就看到什么：
 *   返回字符串  → 一行普通文字
 *   返回数组    → 多行
 *   返回 null   → 这次不出声（合法，别硬凑台词）
 * ========================================================================== */

/* ---------------------------------------------------------------------------
 * 一、给游戏加一条自己的指令
 * 玩家在输入框敲「摸鱼」就能用。指令名随便起，别跟游戏原有的撞（撞了会被拒绝，
 * 「Mod 日志」里会写明）。
 * ------------------------------------------------------------------------- */
wx.command('摸鱼', function () {
  /* wx.state 是随存档保存的账本 —— 第一次访问时是个空对象 */
  var s = wx.state;
  s.moyu = (s.moyu || 0) + 1;

  /* 三成五的概率被师父逮住 */
  if (wx.chance(0.35)) return '你刚把腿翘上横梁，师父的目光就扫了过来。';

  /* 摸到第三回，在墙缝里摸出个东西 —— 内容来自 mod.json，逻辑在脚本里 */
  if (s.moyu >= 3 && wx.count('demo_moyu_charm') === 0) {
    wx.give('demo_moyu_charm', 1);
    return '摸到第三回，你从墙缝里抠出一样东西：「摸鱼符」。';
  }

  wx.money(2); /* 直接加钱（金钱效果不走规则倍率；+exp / +pot 类才会过 gainExp/gainPotential 的倍率） */
  return '你摸了一炷香的鱼，顺带从袖口里捻出 2 文钱。（累计第 ' + s.moyu + ' 次）';
});

/* ---------------------------------------------------------------------------
 * 二、监听世界事件
 *
 * ⚠️ 官方示例**默认不出声**：这个处理器只在玩家（或别的脚本）设了
 *    `demo_script_chatty` 这个变量之后才开始说话 ——
 *    一个自动装上的示例 Mod 不该在你打坐的时候突然插嘴。
 *    想听它说话：在别的脚本里 `wx.set('demo_script_chatty', 1)` 即可。
 * ------------------------------------------------------------------------- */
wx.on('onDayTick', function (info) {
  if (!wx.get('demo_script_chatty')) return null;   /* 没开开关 → 不出声 */
  return '（脚本示例）这是第 ' + ((info && info.day) || '?') + ' 天，你还在江湖上晃着。';
});

/* ---------------------------------------------------------------------------
 * 三、动手前先问一句：这个脚本跑起来了吗？
 * 上面那行会写进「Mod 日志」。装完 Mod 在制作器里翻一眼日志，
 * 能看见「注册了 1 条自定义指令」就说明它真的活着 ——
 * 本项目的头号大坑就是「装了没反应也不报错」，所以这里主动留个脚印。
 * ------------------------------------------------------------------------- */
wx.log('demo_script 已加载：指令「摸鱼」可用。');
